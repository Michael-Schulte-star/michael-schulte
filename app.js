const state = {
  selections: [],
  meetRequest: null,
  contactMethod: null
};

const $ = (id) => document.getElementById(id);
const money = (n, currency="EUR") => new Intl.NumberFormat("en-US", {style:"currency", currency, maximumFractionDigits:0}).format(n);

function formatDate(dateStr) {
  const d = new Date(dateStr + "T12:00:00");
  return {
    day: d.getDate(),
    month: d.toLocaleDateString("en-US", {month:"short"}).toUpperCase(),
    full: d.toLocaleDateString("en-US", {weekday:"short", day:"numeric", month:"long", year:"numeric"})
  };
}

function populateFilters() {
  const tours = [...new Set(DATA.events.map(e => e.tour))];
  tours.forEach(t => $("tourFilter").insertAdjacentHTML("beforeend", `<option value="${escapeHtml(t)}">${escapeHtml(t)}</option>`));
  [...new Set(DATA.events.map(e => e.country))].forEach(c => $("countryFilter").insertAdjacentHTML("beforeend", `<option>${escapeHtml(c)}</option>`));
  DATA.events.forEach((e,i) => {
    $("meetEvent").insertAdjacentHTML("beforeend", `<option value="${i}">${formatDate(e.date).full} — ${escapeHtml(e.city)} · ${escapeHtml(e.venue)}</option>`);
  });
  DATA.countries.forEach(([name]) => $("customerCountry").insertAdjacentHTML("beforeend", `<option>${escapeHtml(name)}</option>`));
}

function escapeHtml(v) {
  return String(v).replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#039;"}[c]));
}

function renderEvents() {
  const tf = $("tourFilter").value, cf = $("countryFilter").value;
  const list = DATA.events.filter(e => (tf === "all" || e.tour === tf) && (cf === "all" || e.country === cf));
  $("eventsGrid").innerHTML = list.map((e) => {
    const d = formatDate(e.date);
    const idx = DATA.events.indexOf(e);
    return `<article class="event-card">
      <span class="tour-tag">${escapeHtml(e.tour)}</span>
      <div class="event-date"><div class="date-box"><b>${d.day}</b><small>${d.month}</small></div><div><strong>${d.full}</strong><div class="muted">${e.time} local time</div></div></div>
      <h3>${escapeHtml(e.city)}, ${escapeHtml(e.country)}</h3>
      <div class="event-meta"><span>📍 ${escapeHtml(e.venue)}</span><span>🎫 Ticket request available</span></div>
      <div class="event-bottom"><button class="btn btn-primary" onclick="addTicket(${idx})">Grab Your Tickets</button></div>
    </article>`;
  }).join("") || `<p class="muted">No events match these filters.</p>`;
}

function renderMemberships() {
  $("membershipGrid").innerHTML = DATA.memberships.map((m,i) => `<article class="member-card ${m.name==="VIP"?"featured":""}">
    <div class="level">${m.name.toUpperCase()}</div><div class="price">${money(m.price)} <small>/ card</small></div>
    <ul class="benefits">${m.benefits.map(b=>`<li>${escapeHtml(b)}</li>`).join("")}</ul>
    <button class="btn btn-primary full" onclick="addMembership(${i})">Select ${m.name}</button>
  </article>`).join("");
}

function renderMerch() {
  $("merchGrid").innerHTML = DATA.merch.map((m,i) => `<article class="merch-card">
    <div class="merch-art">MS</div><h3>${escapeHtml(m.name)}</h3><p class="muted">${escapeHtml(m.description)}</p>
    <div class="merch-price">€${m.price}</div>
    <button class="btn btn-primary full" onclick="addMerch(${i})">Add to inquiry</button>
  </article>`).join("");
}

window.addTicket = (i) => {
  const e = DATA.events[i];
  state.selections.push({type:"Ticket", name:`${e.city} — ${e.venue}`, detail:`${formatDate(e.date).full}, ${e.time} · choose category in inquiry`, qty:1, data:e});
  updateSummary(); scrollToContact();
};
window.addMembership = (i) => {
  const m = DATA.memberships[i];
  state.selections.push({type:"Membership", name:`${m.name} Membership Card`, detail:`€${m.price} per card`, qty:1, data:m});
  updateSummary(); scrollToContact();
};
window.addMerch = (i) => {
  const m = DATA.merch[i];
  state.selections.push({type:"Merchandise", name:m.name, detail:`€${m.price} each`, qty:1, data:m});
  updateSummary(); scrollToContact();
};

function updateSummary() {
  const items = state.selections.map((s,i) => `<div class="summary-item"><div><strong>${escapeHtml(s.name)}</strong><small>${escapeHtml(s.detail)} · Qty ${s.qty}</small></div><button class="remove" onclick="removeItem(${i})">Remove</button></div>`).join("");
  const meet = state.meetRequest ? `<div class="summary-item"><div><strong>${escapeHtml(state.meetRequest.type)}</strong><small>${escapeHtml(state.meetRequest.event.city)} · ${state.meetRequest.guests} guest(s)</small></div><button class="remove" onclick="state.meetRequest=null;updateSummary()">Remove</button></div>` : "";
  $("summary").innerHTML = items + meet || `<p class="muted">Nothing selected yet. Choose a ticket, membership, merchandise or meet request.</p>`;
  updateMessage();
}

window.removeItem = (i) => { state.selections.splice(i,1); updateSummary(); };

function scrollToContact() { $("contact").scrollIntoView({behavior:"smooth"}); }

$("meetAdd").addEventListener("click", () => {
  state.meetRequest = {
    event: DATA.events[Number($("meetEvent").value)],
    guests: Number($("meetGuests").value),
    type: $("meetType").value
  };
  updateSummary(); scrollToContact();
});

function buildMessage() {
  const name = $("customerName").value.trim() || "Customer";
  const country = $("customerCountry").value;
  let lines = [
    `Hello Michael Schulte Management,`,
    ``,
    `My name is ${name} and I would like to make an inquiry from ${country}.`,
    ``
  ];
  if (state.selections.length) {
    lines.push("Selected items:");
    state.selections.forEach((s,i) => {
      lines.push(`${i+1}. ${s.type} — ${s.name} — Qty ${s.qty}`);
      lines.push(`   ${s.detail}`);
    });
    lines.push("");
  }
  if (state.meetRequest) {
    const e = state.meetRequest.event;
    lines.push(`Live experience request: ${state.meetRequest.type}`);
    lines.push(`Show: ${formatDate(e.date).full} — ${e.city}, ${e.country} — ${e.venue}`);
    lines.push(`Guests: ${state.meetRequest.guests}`);
    lines.push("");
  }
  lines.push("Please send me the full details, availability, final pricing and next steps.");
  lines.push("");
  lines.push("Thank you.");
  return lines.join("\n");
}

function updateMessage() {
  $("messagePreview").textContent = buildMessage();
}

document.querySelectorAll(".contact-btn").forEach(btn => btn.addEventListener("click", () => {
  document.querySelectorAll(".contact-btn").forEach(b => b.classList.remove("selected"));
  btn.classList.add("selected"); state.contactMethod = btn.dataset.method; updateMessage();
}));

$("customerName").addEventListener("input", updateMessage);
$("customerCountry").addEventListener("change", updateMessage);

$("copyMessage").addEventListener("click", async () => {
  await navigator.clipboard.writeText(buildMessage());
  $("copyMessage").textContent = "Copied ✓";
  setTimeout(() => $("copyMessage").textContent = "Copy inquiry message", 1500);
});

$("sendMessage").addEventListener("click", () => {
  if (!state.contactMethod) { alert("Please choose your preferred contact method first."); return; }
  const msg = encodeURIComponent(buildMessage());
  const urls = {
    telegram: `https://t.me/michaelschultemanagement`,
    email: `mailto:m.schultemanagement@gmail.com?subject=Michael%20Schulte%20Management%20Inquiry&body=${msg}`
  };
  if (urls[state.contactMethod]) {
    window.open(urls[state.contactMethod], "_blank");
  } else {
    navigator.clipboard.writeText(buildMessage());
    alert(`${state.contactMethod.toUpperCase()} does not expose a universal web deep-link. The inquiry message has been copied to your clipboard. Open ${state.contactMethod} and paste it to ${state.contactMethod==="imo"?"imoid_00DKxlCQBY":"@michaelschultemanagement.02"}.`);
  }
});

